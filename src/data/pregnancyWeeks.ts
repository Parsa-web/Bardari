/** محدود کردن شماره هفته به بازه معتبر ۱ تا ۴۰ */
export function clampPregnancyWeek(week: number): number {
	if (!Number.isFinite(week)) return MIN_PREGNANCY_WEEK
	const rounded = Math.round(week)
	if (rounded < MIN_PREGNANCY_WEEK) return MIN_PREGNANCY_WEEK
	if (rounded > MAX_PREGNANCY_WEEK) return MAX_PREGNANCY_WEEK
	return rounded
}

/** یافتن داده یک هفته؛ اگر هفته معتبر نباشد null برمی‌گردد */
export function getPregnancyWeek(week: number): PregnancyWeekInfo | null {
	return PREGNANCY_WEEKS.find((item) => item.week === week) ?? null
}
